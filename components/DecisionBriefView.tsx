"use client";

import React, { useState } from "react";
import { Signal, PriorityLevel, ActiveTab, FollowUpItem } from "@/types/prio";
import {
  ArrowLeft,
  ArrowRight,
  PlusCircle,
  Check,
  ShieldCheck,
  Sparkles,
  Copy,
  CheckCheck,
  Share2,
} from "lucide-react";

interface DecisionBriefViewProps {
  signals: Signal[];
  summary: string;
  suggestedFocus: string;
  onNavigate: (tab: ActiveTab) => void;
  onSaveFollowUp: (item: Omit<FollowUpItem, "id" | "createdAt">) => void;
  savedFollowUpTitles: Set<string>;
}

export const DecisionBriefView: React.FC<DecisionBriefViewProps> = ({
  signals,
  summary,
  suggestedFocus,
  onNavigate,
  onSaveFollowUp,
  savedFollowUpTitles,
}) => {
  const [copiedBrief, setCopiedBrief] = useState(false);

  const getPriorityBadge = (priority: PriorityLevel) => {
    switch (priority) {
      case "HIGH":
        return (
          <span className="inline-flex items-center px-2 py-0.5 rounded text-[11px] font-bold uppercase tracking-wider bg-red-100 text-red-700 border border-red-200">
            HIGH
          </span>
        );
      case "MEDIUM":
        return (
          <span className="inline-flex items-center px-2 py-0.5 rounded text-[11px] font-bold uppercase tracking-wider bg-amber-100 text-amber-800 border border-amber-200">
            MEDIUM
          </span>
        );
      case "MONITOR":
        return (
          <span className="inline-flex items-center px-2 py-0.5 rounded text-[11px] font-bold uppercase tracking-wider bg-sky-100 text-sky-800 border border-sky-200">
            MONITOR
          </span>
        );
      case "LOW":
        return (
          <span className="inline-flex items-center px-2 py-0.5 rounded text-[11px] font-bold uppercase tracking-wider bg-emerald-100 text-emerald-800 border border-emerald-200">
            LOW
          </span>
        );
      default:
        return null;
    }
  };

  const handleSaveAction = (sig: Signal) => {
    onSaveFollowUp({
      action: sig.suggestedAction || `Resolve: ${sig.title}`,
      owner: sig.category.includes("Sales")
        ? "Sales"
        : sig.category.includes("Customer")
        ? "Product"
        : "Founder",
      dueDate: sig.priority === "HIGH" ? "Today" : "This Week",
      priority: sig.priority,
      status: "Open",
      source: "Decision Brief",
      notes: `Triggered by signal: ${sig.evidence}`,
    });
  };

  const handleCopyMarkdown = () => {
    const lines = [
      `# PrioX — Decision Brief`,
      `**Suggested Focus:** ${suggestedFocus}`,
      `**Summary:** ${summary}`,
      ``,
      `## Key Decisions & Action Items:`,
      ...signals.map(
        (s) =>
          `\n### [${s.priority}] ${s.title}\n- **What Happened:** ${s.evidence}\n- **Why It Matters:** ${s.whyItMatters}\n- **Next Action:** ${s.suggestedAction}`
      ),
      ``,
      `*Generated by PrioX. AI supports your judgment — you make the final decision.*`,
    ];

    navigator.clipboard.writeText(lines.join("\n"));
    setCopiedBrief(true);
    setTimeout(() => setCopiedBrief(false), 2000);
  };

  const highPriorityCount = signals.filter((s) => s.priority === "HIGH").length;

  return (
    <div className="space-y-8 animate-in fade-in duration-200">
      {/* Header */}
      <div className="border-b border-slate-200/80 pb-6">
        <div className="flex flex-col sm:flex-row sm:items-end sm:justify-between gap-4">
          <div>
            <div className="flex items-center space-x-2 text-xs font-semibold uppercase tracking-wider text-blue-600 mb-1">
              <span>Step 4</span>
              <span>•</span>
              <span className="text-slate-400 font-normal">Executive Synthesis</span>
            </div>
            <h1 className="text-3xl sm:text-4xl font-extrabold tracking-tight text-slate-900">
              Decision Brief
            </h1>
            <p className="mt-2 text-base text-slate-600 max-w-2xl">
              What happened • Why it matters • What to consider next
            </p>
          </div>

          <div className="flex items-center space-x-3">
            <button
              onClick={handleCopyMarkdown}
              className="inline-flex items-center space-x-1.5 px-3.5 py-2 text-sm font-medium text-slate-700 bg-white border border-slate-300 hover:bg-slate-50 rounded-lg transition-colors shadow-xs"
            >
              {copiedBrief ? (
                <>
                  <CheckCheck className="w-4 h-4 text-emerald-600" />
                  <span>Copied Brief!</span>
                </>
              ) : (
                <>
                  <Share2 className="w-4 h-4 text-slate-500" />
                  <span>Export Brief</span>
                </>
              )}
            </button>

            <button
              onClick={() => onNavigate("followups")}
              className="inline-flex items-center space-x-2 px-4 py-2 text-sm font-semibold rounded-lg text-white bg-blue-600 hover:bg-blue-700 transition-colors shadow-xs"
            >
              <span>View Follow-ups</span>
              <ArrowRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      </div>

      {/* Dark Contrast Hero Banner: "Today's focus" matching Figma Screen 4 */}
      <div className="bg-slate-900 text-white rounded-xl p-6 sm:p-7 shadow-md relative overflow-hidden">
        <div className="absolute top-0 right-0 w-96 h-96 bg-blue-500/10 rounded-full blur-3xl pointer-events-none" />

        <div className="relative z-10 space-y-3">
          <div className="flex items-center justify-between">
            <span className="inline-flex items-center space-x-1.5 px-2.5 py-1 rounded-md text-xs font-semibold uppercase tracking-wider bg-slate-800 text-blue-400 border border-slate-700">
              <Sparkles className="w-3.5 h-3.5" />
              <span>Today&apos;s Focus</span>
            </span>

            <span className="text-xs text-slate-400 font-medium">
              {highPriorityCount} critical issue{highPriorityCount === 1 ? "" : "s"} requiring attention
            </span>
          </div>

          <h2 className="text-xl sm:text-2xl font-bold tracking-tight text-white leading-snug">
            {suggestedFocus}
          </h2>

          <p className="text-sm text-slate-300 leading-relaxed font-normal max-w-3xl">
            {summary}
          </p>
        </div>
      </div>

      {/* Structured Decision Cards for each Signal */}
      <div className="space-y-6">
        <div className="flex items-center justify-between pb-1">
          <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500">
            Decisions &amp; Proposed Actions ({signals.length})
          </h3>
          <span className="text-xs text-slate-400">
            Save actions directly to your tracker with one click
          </span>
        </div>

        {signals.map((sig) => {
          const isSaved =
            savedFollowUpTitles.has(sig.suggestedAction) ||
            savedFollowUpTitles.has(sig.title) ||
            savedFollowUpTitles.has(`Resolve: ${sig.title}`);

          return (
            <div
              key={sig.id}
              className="bg-white rounded-xl border border-slate-200 shadow-xs overflow-hidden transition-all hover:border-slate-300"
            >
              {/* Card Header */}
              <div className="p-5 border-b border-slate-100 flex flex-wrap items-center justify-between gap-3 bg-slate-50/50">
                <div className="flex items-center space-x-3">
                  {getPriorityBadge(sig.priority)}
                  <span className="text-xs font-bold uppercase tracking-wider text-slate-500">
                    {sig.category}
                  </span>
                  <span className="text-slate-300">•</span>
                  <h4 className="text-base font-bold text-slate-900">
                    {sig.title}
                  </h4>
                </div>

                <button
                  onClick={() => handleSaveAction(sig)}
                  disabled={isSaved}
                  className={`inline-flex items-center space-x-1.5 px-3.5 py-1.5 text-xs font-semibold rounded-lg border transition-all ${
                    isSaved
                      ? "bg-emerald-50 text-emerald-700 border-emerald-200 cursor-default"
                      : "bg-blue-600 hover:bg-blue-700 text-white border-transparent shadow-xs"
                  }`}
                >
                  {isSaved ? (
                    <>
                      <Check className="w-3.5 h-3.5 text-emerald-600" />
                      <span>Saved to Tracker</span>
                    </>
                  ) : (
                    <>
                      <PlusCircle className="w-3.5 h-3.5" />
                      <span>Save as Follow-up</span>
                    </>
                  )}
                </button>
              </div>

              {/* Card Body: 3 Structured Columns (What Happened, Why It Matters, Possible Next Action) */}
              <div className="grid grid-cols-1 md:grid-cols-3 divide-y md:divide-y-0 md:divide-x divide-slate-100 text-xs">
                {/* Column 1: WHAT HAPPENED */}
                <div className="p-5 space-y-2">
                  <span className="font-extrabold uppercase tracking-wider text-slate-400 block text-[10px]">
                    What Happened
                  </span>
                  <p className="text-slate-800 font-medium leading-relaxed">
                    {sig.evidence}
                  </p>
                </div>

                {/* Column 2: WHY IT MATTERS */}
                <div className="p-5 space-y-2">
                  <span className="font-extrabold uppercase tracking-wider text-slate-400 block text-[10px]">
                    Why It Matters
                  </span>
                  <p className="text-slate-700 leading-relaxed">
                    {sig.whyItMatters}
                  </p>
                </div>

                {/* Column 3: POSSIBLE NEXT ACTION */}
                <div className="p-5 space-y-2 bg-blue-50/20">
                  <span className="font-extrabold uppercase tracking-wider text-blue-600 block text-[10px]">
                    Possible Next Action
                  </span>
                  <p className="text-blue-950 font-semibold leading-relaxed">
                    {sig.suggestedAction}
                  </p>
                </div>
              </div>
            </div>
          );
        })}
      </div>

      {/* Navigation Controls */}
      <div className="flex flex-col sm:flex-row items-center justify-between gap-4 pt-4 border-t border-slate-200">
        <button
          onClick={() => onNavigate("analysis")}
          className="inline-flex items-center space-x-1.5 px-4 py-2 text-sm font-medium text-slate-700 bg-white border border-slate-300 hover:bg-slate-50 rounded-lg transition-colors shadow-xs"
        >
          <ArrowLeft className="w-4 h-4" />
          <span>Back to Analysis</span>
        </button>

        <button
          onClick={() => onNavigate("followups")}
          className="inline-flex items-center space-x-2 px-5 py-2.5 text-sm font-bold text-white bg-blue-600 hover:bg-blue-700 rounded-lg transition-colors shadow-xs"
        >
          <span>Go to Follow-up Tracker</span>
          <ArrowRight className="w-4 h-4" />
        </button>
      </div>

      {/* Mandatory Bottom Product Disclaimer */}
      <div className="p-4 rounded-xl bg-slate-100 border border-slate-200 text-center text-xs text-slate-600 font-medium flex items-center justify-center space-x-2">
        <ShieldCheck className="w-4 h-4 text-slate-500" />
        <span>AI supports your judgment — you make the final decision.</span>
      </div>
    </div>
  );
};
